// Compress the transition near a physical tone. This retains smooth ramps
// while avoiding isolated specks in regions already close to a supported gray.
constexpr uint8_t gray4(const uint8_t luminance, const unsigned x, const unsigned y) {
  // Lift shadows and midtones with a monotonic curve that keeps black and white fixed.
  const unsigned lifted = luminance + (luminance * (255 - luminance) + 255) / 510;
  const unsigned lower = lifted / 85;
  const int remainder = lifted % 85;
  constexpr int quietZone = 6;
  constexpr int span = 85 - quietZone * 2;
  const int blend = remainder - quietZone;
  const int threshold = kThresholds[(y & 31) * 32 + (x & 31)];
  return static_cast<uint8_t>((lower + (blend > 0 && blend * 256 > threshold * span)) * 85);
}

// The retained UI waveform has one middle tone. Mix adjacent visible tones
// so thumbnails keep contrast without switching the whole page to the photo waveform.
constexpr uint8_t coverGray(const uint8_t luminance, const unsigned x, const unsigned y) {
  constexpr unsigned midpoint = 128;
  constexpr unsigned quietZone = 8;
  const unsigned lifted = luminance + (luminance * (255 - luminance) + 510) / 1020;
  const bool lightHalf = lifted >= midpoint;
  const unsigned offset = lightHalf ? lifted - midpoint : lifted;
  const unsigned range = lightHalf ? 255 - midpoint : midpoint;
  const unsigned threshold = kThresholds[(y & 31) * 32 + (x & 31)];
  if (offset > quietZone && (offset - quietZone) * 256 > threshold * (range - 2 * quietZone)) {
    return lightHalf ? 255 : 170;
  }
  return lightHalf ? 170 : 0;
}
