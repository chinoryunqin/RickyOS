#!/usr/bin/env python3
"""Write the Plus TTF pre-rasterization list: the first N characters of the design's
frequency order (ASCII and punctuation first, then CJK by use)."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'firmware/rickyos-plus-1.2/upstream/lib/EpdFont/scripts/cn_rickyos_group_order.txt'
OUTPUT = ROOT / 'firmware/rickyos-plus-1.2/components/rickyos_application/port/PlusCommonChars.h'
COUNT = 4000


def render():
    chars = [c for c in SOURCE.read_text(encoding='utf-8') if c not in '\r\n'][:COUNT]
    data = ''.join(chars).encode('utf-8')
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return ('#pragma once\n\n'
            '// Generated by scripts/generate_plus_common_chars.py from upstream\n'
            f'// lib/EpdFont/scripts/cn_rickyos_group_order.txt (first {len(chars)} characters). Do not edit.\n'
            '// UTF-8, NUL-terminated: the order the Plus pre-rasterizes a TTF reader face in.\n\n'
            '#include <cstdint>\n\n'
            'inline constexpr uint8_t kPlusCommonChars[] = {\n  ' + ',\n  '.join(rows) + ', 0x00};\n')


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUTPUT.exists() and OUTPUT.read_text() == text else 'PlusCommonChars.h is stale')
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT.relative_to(ROOT)}')
