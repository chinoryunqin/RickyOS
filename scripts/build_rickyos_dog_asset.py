#!/usr/bin/env python3
"""Encode the approved mockup's dog (not the portrait ring) as native coverage.

Developer-only Pillow dependency. No image reinterpretation or run-time buffers.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/design-system/mockup-src/dog.png"
OUTPUT = ROOT / "src/images/RickyDog.h"


def main():
    image = Image.open(SOURCE).convert("RGBA")
    paper = Image.new("RGBA", image.size, "white")
    gray = Image.alpha_composite(paper, image).convert("L")
    levels = [round((255 - value) / 17) for value in gray.tobytes()]
    packed = [(levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2)]
    lines = [
        "#pragma once", "", "#include <cstdint>", "",
        "// Generated by scripts/build_rickyos_dog_asset.py from the approved design asset.",
        "// 4-bit coverage: 0 paper, 15 ink; no palette or heap allocation.",
        "namespace RickyDogAsset {",
        f"inline constexpr int width = {image.width}, height = {image.height};",
        "inline constexpr uint8_t coverage[] = {",
    ]
    for i in range(0, len(packed), 19):
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in packed[i:i + 19]) + ",")
    lines += ["};", "}  // namespace RickyDogAsset", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"{OUTPUT.name}: {image.width} x {image.height}, {len(packed)} Flash bytes")


if __name__ == "__main__":
    main()
