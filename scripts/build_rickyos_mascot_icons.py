#!/usr/bin/env python3
"""RickyOS reading-stats mascot (the brand puppy in three moods) -> 1-bpp Flash icons.

Sources: src/components/icons/sources/rickyos/mascot/{sleeping,cheering,happy}.png, drawn with
codex image generation against the character sheets (docs/brand/rickyos-characters.md): asleep
before today's reading, cheering the reader on, jumping for joy at the goal. The puppy never
holds a book. Each is trimmed to its ink, centered on a square, resized to SIZE and thresholded; light gray fills become paper, outlines and patches stay ink.
Run: python3 scripts/build_rickyos_mascot_icons.py [--out header.h]
"""
import argparse
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "src/components/icons/sources/rickyos/mascot"
CAT_SOURCES = ROOT / "src/components/icons/sources/rickyos/mascot-cat"  # the cat theme, same moods
NAMES = ("sleeping", "cheering", "happy")
SIZE = 150
SMALL_SIZE = 88  # the home page's today card
THRESHOLD = 110


def icon(path: Path, size: int = SIZE) -> bytes:
    gray = Image.open(path).convert("L")
    box = ImageOps.invert(gray).point(lambda v: 255 if v > 60 else 0).getbbox()
    art = gray.crop(box) if box else gray
    side = max(art.size) + 8
    square = Image.new("L", (side, side), 255)
    square.paste(art, ((side - art.width) // 2, (side - art.height) // 2))
    small = square.resize((size, size), Image.LANCZOS)
    row = (size + 7) // 8
    bits = bytearray([0xFF] * (row * size))
    for y in range(size):
        for x in range(size):
            if small.getpixel((x, y)) < THRESHOLD:
                bits[y * row + x // 8] &= ~(0x80 >> (x % 8)) & 0xFF
    return bytes(bits)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "src/components/icons/rickyMascotIcons.h")
    args = parser.parse_args()
    lines = ["#pragma once", "", "#include <cstdint>", "",
             "// Generated by scripts/build_rickyos_mascot_icons.py from sources/rickyos/mascot/*.png.",
             f"// {SIZE} x {SIZE} (and {SMALL_SIZE} x {SMALL_SIZE} for the home card), MSB-first, 1 = paper,",
             "// 0 = ink. Regenerate; never edit these bytes.", "",
             f"inline constexpr int kRickyMascotSize = {SIZE};",
             f"inline constexpr int kRickyMascotSmallSize = {SMALL_SIZE};", ""]
    for prefix, size, sources in (("ricky_mascot", SIZE, SOURCES), ("ricky_mascot_small", SMALL_SIZE, SOURCES),
                                  ("ricky_cat", SIZE, CAT_SOURCES), ("ricky_cat_small", SMALL_SIZE, CAT_SOURCES)):
        for name in NAMES:
            data = icon(sources / f"{name}.png", size)
            lines.append(f"static constexpr uint8_t {prefix}_{name}[] = {{")
            for offset in range(0, len(data), 19):  # clang-format packs 19 per line
                lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[offset:offset + 19]) + ",")
            lines += ["};", ""]
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
