"""Pack the ordinary panel's existing font tables without changing any glyph.

The bitmap groups stay in flash. One bounded PSRAM allocation holds the decoded
glyph and Unicode tables for both permanent fallback faces, with shared tables
stored once. Normal builds need only Python's standard library.
"""
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
FACES = ("metalio_body_10_regular", "metalio_book_10_medium")
SCHEMAS = (("EpdGlyph", "Glyphs", "<BBHhhH2xI"), ("EpdUnicodeInterval", "Intervals", "<III"))


def write_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def pack():
    output = ROOT / "generated/native-font-metadata"
    tables = {}
    faces = []
    total_raw = 0
    pool_bytes = 0
    for name in FACES:
        source = ROOT / "generated/fonts" / (name + ".packed.h")
        text = source.read_text()
        face = {"name": name, "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest()}
        for ctype, suffix, fmt in SCHEMAS:
            symbol = name + suffix
            match = re.search(r"static const " + ctype + " " + symbol + r"\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
            if not match:
                raise ValueError(f"{source}: missing {symbol}")
            rows = [[int(value.strip(), 0) for value in row.split(",") if value.strip()]
                    for row in re.findall(r"\{([^{}]+)\}", match[1])]
            raw = b"".join(struct.pack(fmt, *row) for row in rows)
            stride = struct.calcsize(fmt)
            digest = hashlib.sha256(raw).hexdigest()
            total_raw += len(raw)
            if digest not in tables:
                delta = bytes((byte - (raw[i - stride] if i >= stride else 0)) & 255 for i, byte in enumerate(raw))
                wrapped = zlib.compress(delta, 9)
                stream = wrapped[2:-4]
                decoded = bytearray(zlib.decompress(stream, -15))
                for i in range(stride, len(decoded)):
                    decoded[i] = (decoded[i] + decoded[i - stride]) & 255
                if decoded != raw:
                    raise ValueError(f"{symbol}: roundtrip mismatch")
                checksum = 2166136261
                for byte in raw:
                    checksum = ((checksum ^ byte) * 16777619) & 0xffffffff
                tables[digest] = dict(offset=pool_bytes, size=len(raw), stride=stride,
                                      stream=stream, checksum=checksum)
                # An extra aligned record allows the inflater to consume its end marker.
                pool_bytes += len(raw) + stride
            table = tables[digest]
            face[suffix] = table["offset"]
            face[suffix + "Count"] = len(rows)
            text = text[:match.start()] + text[match.end():]
            text = re.sub(r"\b" + symbol + r"\b", "nullptr", text)
        pattern = r"static const EpdFontData " + name + r" = \{(\s*[^,]+,\s*nullptr,\s*nullptr,\s*)\d+,"
        text, count = re.subn(pattern, r"static EpdFontData " + name + r" = {\g<1>0,", text)
        if count != 1:
            raise ValueError(f"{source}: font descriptor changed")
        write_changed(output / "nativefontmeta" / (name + ".packed.h"),
                      "// Generated by pack_metalio_font_metadata.py. Do not edit.\n" + text)
        faces.append(face)

    if pool_bytes > 320 * 1024:
        raise ValueError("Native font tables exceed the explicit 320 KiB PSRAM budget")
    lines = ["// Generated by pack_metalio_font_metadata.py. Do not edit.",
             "static_assert(sizeof(EpdGlyph) == 16 && offsetof(EpdGlyph, dataOffset) == 12);",
             "static_assert(sizeof(EpdUnicodeInterval) == 12);",
             f"constexpr size_t kNativeFontMetadataBytes = {pool_bytes};"]
    for i, table in enumerate(tables.values()):
        lines.append(f"static const uint8_t kPackedTable{i}[] = {{")
        stream = table["stream"]
        lines.extend("  " + ",".join(str(byte) for byte in stream[pos:pos + 24]) + ","
                     for pos in range(0, len(stream), 24))
        lines.append("};")
    lines.append("static const NativeMetadataTable kNativeMetadataTables[] = {")
    for i, table in enumerate(tables.values()):
        lines.append(f'  {{kPackedTable{i}, sizeof(kPackedTable{i}), {table["offset"]}, '
                     f'{table["size"]}, {table["stride"]}, 0x{table["checksum"]:08x}U}},')
    lines.append("};")
    lines.append("static const NativeFontOffsets kNativeFontOffsets[] = {")
    for face in faces:
        lines.append(f'  {{{face["Glyphs"]}, {face["Intervals"]}, {face["IntervalsCount"]}}},')
    lines.append("};")
    write_changed(output / "NativeFontMetadata.generated.inc", "\n".join(lines) + "\n")
    report = dict(original_flash_bytes=total_raw, compressed_flash_bytes=sum(len(t["stream"]) for t in tables.values()),
                  psram_bytes=pool_bytes, faces=faces)
    write_changed(output / "packing-report.json", json.dumps(report, indent=2) + "\n")
    print(f'Native font metadata: {total_raw} -> {report["compressed_flash_bytes"]} flash bytes, '
          f'{pool_bytes} PSRAM bytes; all tables roundtrip verified')


if __name__ == "__main__":
    pack()
