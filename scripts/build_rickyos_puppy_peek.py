#!/usr/bin/env python3
"""The brand puppy peeking over an edge -> the home card's peek and the 小狗伴读 frame's peek.

Source: src/images/sources/rickyos/puppy-peek.png, drawn against the character sheets
(docs/brand/rickyos-characters.md): head and front paws above one full-width edge line.
Everything above the line is the art; the line itself is left to the UI (the card's top
edge, the reading frame), and the paws rest on it.

Outputs
  src/images/RickyDog.h                 home: 4-bit coverage, 0 paper .. 15 ink; paper is not drawn
  src/components/icons/rickyReaderDog.h 小狗伴读: 2-bit gray (0 ink .. 3 paper) plus a 1-bit mask of the
                                        silhouette, so the head's paper hides the frame line behind it

Developer-only: Pillow.
Run: python3 scripts/build_rickyos_puppy_peek.py [--home header.h] [--reader header.h] [--preview png]
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/images/sources/rickyos/puppy-peek.png'
HOME = ROOT / 'src/images/RickyDog.h'
READER = ROOT / 'src/components/icons/rickyReaderDog.h'
HOME_HEIGHT = 90
READER_HEIGHT = 96
INK = 128


def art_above_edge(source: Path = SOURCE) -> Image.Image:
    """The drawing cropped to its ink above the edge line, white paper, 8-bit gray."""
    gray = Image.open(source).convert('L')
    width, height = gray.size
    pixels = gray.load()
    # The edge is the topmost row that is ink nearly all the way across.
    edge = next(y for y in range(height) if sum(pixels[x, y] < INK for x in range(width)) > width * 0.9)
    above = gray.crop((0, 0, width, edge))
    # The line's soft upper rows span the whole width; measure the drawing clear of them. A
    # thicker line starts a few rows above `edge`, so step back to its first wide row.
    line_top = edge
    while line_top > 0 and sum(pixels[x, line_top - 1] < INK for x in range(width)) > width * 0.75:
        line_top -= 1
    left, top, right, _ = above.crop((0, 0, width, line_top - 6)).point(lambda v: 255 if v < INK else 0).getbbox()
    # Below the measured band only the paws meet the line; keep their rows but wipe the line's fringe.
    art = above.crop((left, top, right, edge))
    return art.point(lambda v: 255 if v > 200 else v)


def resized(art: Image.Image, height: int) -> Image.Image:
    width = round(art.width * height / art.height)
    return art.resize((width, height), Image.LANCZOS)


def silhouette(image: Image.Image) -> Image.Image:
    """1 inside the puppy (ink or enclosed paper), 0 outside. The open bottom (the edge) is closed first."""
    ink = image.point(lambda v: 0 if v < INK else 255)
    padded = Image.new('L', (ink.width + 2, ink.height + 2), 255)
    padded.paste(ink, (1, 1))
    ImageDraw.Draw(padded).line((0, padded.height - 1, padded.width, padded.height - 1), fill=0)
    ImageDraw.floodfill(padded, (0, 0), 128)
    inside = padded.crop((1, 1, ink.width + 1, ink.height + 1))
    return inside.point(lambda v: 0 if v == 128 else 1)


def rows(data: bytes, per_line: int = 19):
    for start in range(0, len(data), per_line):
        yield '    ' + ' '.join(f'0x{b:02X},' for b in data[start:start + per_line])


def home_header(art: Image.Image, source: Path = SOURCE, namespace: str = 'RickyDogAsset') -> str:
    image = resized(art, HOME_HEIGHT)
    levels = [round((255 - v) / 17) for v in image.tobytes()]
    if len(levels) % 2:
        levels.append(0)
    packed = bytes((levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2))
    return '\n'.join([
        '#pragma once', '', '#include <cstdint>', '',
        f'// Generated by scripts/build_rickyos_puppy_peek.py from {source.relative_to(ROOT)}.',
        '// The home card\'s peeking companion. 4-bit coverage: 0 paper, 15 ink; no palette or heap allocation.',
        f'namespace {namespace} {{',
        f'inline constexpr int width = {image.width}, height = {image.height};',
        'inline constexpr uint8_t coverage[] = {', *rows(packed), '};',
        f'}}  // namespace {namespace}', '',
    ])


def reader_header(art: Image.Image, source: Path = SOURCE, namespace: str = 'RickyReaderDog') -> str:
    image = resized(art, READER_HEIGHT)
    mask = silhouette(image)
    width, height = image.size
    gray_stride, mask_stride = (width + 3) // 4, (width + 7) // 8
    gray, bits = bytearray(), bytearray()
    for y in range(height):
        row = bytearray(gray_stride)
        mrow = bytearray(mask_stride)
        for x in range(width):
            level = min(3, image.getpixel((x, y)) * 4 // 256)  # 0 ink .. 3 paper
            row[x // 4] |= level << (6 - 2 * (x % 4))
            if mask.getpixel((x, y)):
                mrow[x // 8] |= 0x80 >> (x % 8)
        gray += row
        bits += mrow
    return '\n'.join([
        '#pragma once', '', '#include <cstdint>', '',
        f'// Generated by scripts/build_rickyos_puppy_peek.py from {source.relative_to(ROOT)}.',
        '// 伴读: the companion peeking over the reading frame. 2-bit gray, 0 ink .. 3 paper, MSB-first;',
        '// the mask marks the silhouette (drawn, paper included) so the frame line hides behind the head.',
        f'namespace {namespace} {{',
        f'inline constexpr int kWidth = {width};',
        f'inline constexpr int kHeight = {height};',
        '// The frame line\'s lower row: the paws rest on it, just below the art.',
        f'inline constexpr int kEdgeRow = {height};',
        f'inline constexpr int kGrayStride = {gray_stride};',
        f'inline constexpr int kMaskStride = {mask_stride};',
        'inline constexpr uint8_t kGray[] = {', *rows(bytes(gray)), '};',
        'inline constexpr uint8_t kMask[] = {', *rows(bytes(bits)), '};',
        f'}}  // namespace {namespace}', '',
    ])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--home', type=Path, default=HOME)
    parser.add_argument('--reader', type=Path, default=READER)
    parser.add_argument('--preview', type=Path)
    parser.add_argument('--source', type=Path, default=SOURCE)
    parser.add_argument('--home-namespace', default='RickyDogAsset')
    parser.add_argument('--reader-namespace', default='RickyReaderDog')
    parser.add_argument('--cat', action='store_true',
                        help='the cat theme: cat-peek.png -> RickyCat.h / rickyReaderCat.h')
    args = parser.parse_args()
    if args.cat:
        args.source = ROOT / 'src/images/sources/rickyos/cat-peek.png'
        args.home = ROOT / 'src/images/RickyCat.h'
        args.reader = ROOT / 'src/components/icons/rickyReaderCat.h'
        args.home_namespace, args.reader_namespace = 'RickyCatAsset', 'RickyReaderCat'
    source = args.source.resolve()
    art = art_above_edge(source)
    args.home.write_text(home_header(art, source, args.home_namespace))
    args.reader.write_text(reader_header(art, source, args.reader_namespace))
    if args.preview:
        home, reader = resized(art, HOME_HEIGHT), resized(art, READER_HEIGHT)
        sheet = Image.new('L', (home.width + reader.width + 60, READER_HEIGHT + 40), 255)
        sheet.paste(home, (20, 20 + READER_HEIGHT - HOME_HEIGHT))
        sheet.paste(reader, (40 + home.width, 20))
        ImageDraw.Draw(sheet).line((0, 20 + READER_HEIGHT, sheet.width, 20 + READER_HEIGHT), fill=0, width=2)
        sheet.save(args.preview)


if __name__ == '__main__':
    main()
