#!/usr/bin/env python3
"""Pinned MIT pypinyin data -> bounded, flash-resident simplified IME table.

No firmware build needs Python packages or network. Commit generated header
with this recipe. Only GB2312 Han characters are retained (existing UI fallback).
The priority list is original product data, not a scraped commercial lexicon.
"""
import hashlib
import json
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = "https://raw.githubusercontent.com/mozillazg/python-pinyin/v0.55.0/pypinyin/pinyin_dict.json"
SHA256 = "5f294c01e6c6c0a1c8e329c79335a3f8e0b27d06bf1de7a99244b765892d1e5b"
COMMON = "的一是不了人我在有他这中大来上国个到说们为子和你地出道也时年得就那要下以生会自着去之过家学对可她里后小心多天而能好都然没日于起还发成只如事把无明看本面知现所同手时方女新前想最太见被高用开么将行长身三间加由其从两情进已又些点样意力第话走实定才爱亲当问比很世书水名作每海边信安静远山慢读清晨章客花月风雨空云春夏秋冬"


def normalize(value):
    # Tone-bearing ü is precomposed (e.g. ǜ). Preserve the diaeresis BEFORE
    # dropping tones, otherwise lü incorrectly merges into lu.
    value = unicodedata.normalize("NFD", value).replace("u\u0308", "v")
    return "".join(c for c in value if not unicodedata.combining(c)).lower()


def main():
    data = urllib.request.urlopen(URL, timeout=30).read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise SystemExit("pypinyin checksum mismatch")
    groups = {}
    # Never offer a character the shipped product body font cannot display.
    supported = set((ROOT / "lib/EpdFont/scripts/cn_rickyos_chars.txt").read_text())
    rank = {ord(c): i for i, c in reversed(list(enumerate(COMMON)))}
    for point, readings in json.loads(data).items():
        cp = int(point)
        if not 0x4e00 <= cp <= 0x9fff or chr(cp) not in supported:
            continue
        try:
            chr(cp).encode("gb2312")
        except UnicodeEncodeError:
            continue
        for syllable in {normalize(p) for p in readings.split(",")}:
            if syllable.isascii() and syllable.isalpha() and len(syllable) <= 6:
                groups.setdefault(syllable, set()).add(cp)
    points, rows = [], []
    for syllable, chars in sorted(groups.items()):
        ordered = sorted(chars, key=lambda cp: (rank.get(cp, 10000), chr(cp).encode("gb2312")))
        code = 0
        for char in syllable.ljust(6, "\0"):
            code = (code << 5) | (ord(char) - ord("a") + 1 if char != "\0" else 0)
        rows.append(f'  {{{code}u, {len(points)}, {len(ordered)}}}, // {syllable}')
        points.extend(ordered)
    header = ["// Generated by scripts/build_pinyin_dictionary.py. SPDX-License-Identifier: MIT",
              "// pypinyin v0.55.0; copyright/permission: data/ime/LICENSE.pypinyin.txt",
              "#pragma once", "#include <cstdint>", "namespace ricky_pinyin_data {",
              "struct Syllable { uint32_t key; uint16_t offset; uint16_t count; };",
              "inline constexpr Syllable syllables[] = {", *rows, "};",
              "inline constexpr uint16_t characters[] = {"]
    for i in range(0, len(points), 16):
        header.append("  " + ", ".join(str(cp) for cp in points[i:i+16]) + ",")
    header.extend(["};", "}", ""])
    (ROOT / "src/util/PinyinDictionary.h").write_text("\n".join(header))
    print(f"{len(groups)} syllables, {len(set(points))} characters, {len(points)} readings; flash table {len(points)*2 + len(rows)*8} bytes")


if __name__ == "__main__":
    main()
