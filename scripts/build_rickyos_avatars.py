#!/usr/bin/env python3
"""Default RickyOS avatars: the brand puppy and its animal friends, in the brand character style.

The sources are PNG drawings in src/images/sources/rickyos/avatars/: the puppy is cut from the
character sheet, the friends were drawn with an image model against docs/brand/characters/
(see docs/brand/rickyos-characters.md) and are kept as the editable originals. Each
is cropped to its ink, centred inside the circle the firmware masks to, reduced to
160 px and thresholded to 1 bit. Smaller avatars are area-sampled at draw time.

Run: python3 scripts/build_rickyos_avatars.py [--out header.h] [--preview sheet.png]
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'src/images/sources/rickyos/avatars'
HEADER = ROOT / 'src/components/icons/rickyAvatars.h'
SIZE = 160
# Settings store "@avatar:<index>": this order is persistent and must never change.
AVATARS = [
    ('dog', 'The brand puppy (the default avatar), cut from docs/brand/characters/puppy_expressions.png'),
    ('cat', 'Cat in a scarf'),
    ('rabbit', 'Rabbit in a beret'),
    ('bear', 'Bear with headphones'),
    ('panda', 'Panda in a bow tie'),
    ('fox', 'Fox in a collar'),
    ('owl', 'Owl in round glasses'),
    ('penguin', 'Penguin in a beanie'),
    ('koala', 'Koala in a bucket hat'),
]
INK_LEVEL = 128     # source pixels darker than this count as ink when finding the drawing
THRESHOLD = 150     # after reduction: a pixel this dark or darker becomes ink
FILL = 0.80         # share of the circle's diameter the drawing's width may take
TOP = 0.10          # top margin, as a share of the circle's diameter


def to_bits(path: Path) -> Image.Image:
    source = Image.open(path).convert('L')
    box = source.point(lambda v: 255 if v < INK_LEVEL else 0).getbbox()
    if box is None:
        raise SystemExit(f'{path.name}: no ink found')
    left, top, right, bottom = box
    # Fit the width; a portrait's shoulders may run off the bottom of the circle, its ears may not.
    side = int(max(right - left, (bottom - top) * 0.9) / FILL)
    cx = (left + right) // 2
    canvas = Image.new('L', (side, side), 255)
    canvas.paste(source.crop(box), (side // 2 - (cx - left), int(side * TOP)))
    small = canvas.resize((SIZE, SIZE), Image.LANCZOS)
    return small.point(lambda v: 0 if v <= THRESHOLD else 255).convert('1')


def header_text(images) -> str:
    lines = [
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        '// Generated by scripts/build_rickyos_avatars.py from the drawings in',
        '// src/images/sources/rickyos/avatars/. Edit the sources and regenerate; never these bytes.',
        f'// {SIZE}x{SIZE}, MSB-first, 1 = paper, 0 = ink. Area-sampled down at draw time.',
        '',
        'namespace RickyAvatars {',
        f'inline constexpr int SIZE = {SIZE};',
    ]
    for (name, label), image in zip(AVATARS, images):
        data = image.tobytes()  # mode '1' packs MSB-first, 1 = white
        lines.append(f'// {label}')
        lines.append(f'inline constexpr uint8_t {name}[] = {{')
        for start in range(0, len(data), 19):
            lines.append('    ' + ' '.join(f'0x{b:02X},' for b in data[start:start + 19]))
        lines.append('};')
    names = ', '.join(name for name, _ in AVATARS)
    lines.append(f'inline constexpr const uint8_t* ALL[] = {{{names}}};')
    lines.append(f'inline constexpr int COUNT = {len(AVATARS)};')
    lines.append('}  // namespace RickyAvatars')
    return '\n'.join(lines) + '\n'


def drawn(image: Image.Image, size: int) -> Image.Image:
    """The firmware's draw: area-sampled, ink where 7/16 of the source is ink, circle mask and ring."""
    src = image.load()
    out = Image.new('1', (size, size), 1)
    dst = out.load()
    for y in range(size):
        sy0, sy1 = y * SIZE // size, max(y * SIZE // size + 1, (y + 1) * SIZE // size)
        for x in range(size):
            sx0, sx1 = x * SIZE // size, max(x * SIZE // size + 1, (x + 1) * SIZE // size)
            covered = sum(1 for sy in range(sy0, sy1) for sx in range(sx0, sx1) if src[sx, sy] == 0)
            if covered * 16 >= 7 * (sy1 - sy0) * (sx1 - sx0):
                dst[x, y] = 0
    mask = Image.new('1', (size, size), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size - 1, size - 1), fill=1)
    out = Image.composite(out, Image.new('1', (size, size), 1), mask)
    ImageDraw.Draw(out).ellipse((0, 0, size - 1, size - 1), outline=0, width=max(2, size // 48))
    return out


def preview(images, path: Path) -> None:
    sizes = (SIZE, 88, 56)
    gap = 16
    width = len(images) * (SIZE + gap) + gap
    height = gap + sum(s + gap for s in sizes)
    sheet = Image.new('1', (width, height), 1)
    y = gap
    for size in sizes:
        for i, image in enumerate(images):
            x = gap + i * (SIZE + gap) + (SIZE - size) // 2
            sheet.paste(drawn(image, size), (x, y))
        y += size + gap
    sheet.save(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=HEADER)
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    images = [to_bits(SOURCES / f'{name}.png') for name, _ in AVATARS]
    args.out.write_text(header_text(images))
    if args.preview:
        preview(images, args.preview)


if __name__ == '__main__':
    main()
