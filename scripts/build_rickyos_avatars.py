#!/usr/bin/env python3
"""Default RickyOS avatars: the brand puppy and its animal friends, in the brand character style.

The sources are PNG drawings in src/images/sources/rickyos/avatars/: the puppy is cut from the
character sheet, the friends were drawn with an image model against docs/brand/characters/
(see docs/brand/rickyos-characters.md) and are kept as the editable originals. Each
is cropped to its ink, centred inside the circle the firmware masks to, reduced to
160 px and kept as 4-bit ink coverage, run-length coded (line art is mostly long runs of
paper or ink, so this is about the size a 1-bit copy would be). The firmware area-samples
it down at draw time: graded edges on a 16-level frame, the 1-bit threshold otherwise.

Run: python3 scripts/build_rickyos_avatars.py [--out header.h] [--preview sheet.png]
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'src/images/sources/rickyos/avatars'
HEADER = ROOT / 'src/components/icons/rickyAvatars.h'
SIZE = 160
# Settings store "@avatar:<index>": this order is persistent and must never change.
AVATARS = [
    ('dog', 'The brand puppy (the default avatar), cut from docs/brand/characters/puppy_expressions.png'),
    ('cat', 'Cat in a scarf'),
    ('rabbit', 'Rabbit in a beret'),
    ('bear', 'Bear with headphones'),
    ('panda', 'Panda in a bow tie'),
    ('fox', 'Fox in a collar'),
    ('owl', 'Owl in round glasses'),
    ('penguin', 'Penguin in a beanie'),
    ('bichon', 'Bichon in a bandana (replaced the koala, same slot)'),
]
# The default avatar (index 0) follows Profile -> Theme: the cat theme shows this instead of the puppy.
CAT_DEFAULT = ('catDefault', 'theme-cat', 'The cat theme\'s default avatar: the P1 white kitten')
INK_LEVEL = 128     # source pixels darker than this count as ink when finding the drawing
FILL = 0.80         # share of the circle's diameter the drawing's width may take
TOP = 0.10          # top margin, as a share of the circle's diameter


def to_coverage(path: Path, fill: float = FILL, top: float = TOP) -> Image.Image:
    """The drawing at SIZE px as ink coverage 0 (paper) .. 15 (ink)."""
    source = Image.open(path).convert('L')
    box = source.point(lambda v: 255 if v < INK_LEVEL else 0).getbbox()
    if box is None:
        raise SystemExit(f'{path.name}: no ink found')
    left, top_, right, bottom = box
    # Fit the width; a portrait's shoulders may run off the bottom of the circle, its ears may not.
    side = int(max(right - left, (bottom - top_) * 0.9) / fill)
    cx = (left + right) // 2
    canvas = Image.new('L', (side, side), 255)
    canvas.paste(source.crop(box), (side // 2 - (cx - left), int(side * top)))
    small = canvas.resize((SIZE, SIZE), Image.LANCZOS)
    return small.point(lambda v: (255 - v) * 15 // 255 if v < 248 else 0)


def rle(image: Image.Image) -> bytes:
    """byte = (run - 1) << 4 | coverage, row-major, runs of up to 16."""
    values = image.tobytes()
    out = bytearray()
    i = 0
    while i < len(values):
        j = i
        while j < len(values) and values[j] == values[i] and j - i < 16:
            j += 1
        out.append((j - i - 1) << 4 | values[i])
        i = j
    return bytes(out)


def header_text(images, cat_default) -> str:
    lines = [
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        '// Generated by scripts/build_rickyos_avatars.py from the drawings in',
        '// src/images/sources/rickyos/avatars/. Edit the sources and regenerate; never these bytes.',
        f'// {SIZE}x{SIZE} ink coverage, 0 = paper .. 15 = ink, row-major, run-length coded:',
        '// byte = (run - 1) << 4 | coverage. Area-sampled down at draw time.',
        '',
        'namespace RickyAvatars {',
        f'inline constexpr int SIZE = {SIZE};',
    ]
    lengths = []
    for (name, label), image in zip(AVATARS, images):
        data = rle(image)
        lengths.append(len(data))
        lines.append(f'// {label}')
        lines.append(f'inline constexpr uint8_t {name}[] = {{')
        for start in range(0, len(data), 19):
            lines.append('    ' + ' '.join(f'0x{b:02X},' for b in data[start:start + 19]))
        lines.append('};')
    name, _, label = CAT_DEFAULT
    data = rle(cat_default)
    lines.append(f'// {label}')
    lines.append(f'inline constexpr uint8_t {name}[] = {{')
    for start in range(0, len(data), 19):
        lines.append('    ' + ' '.join(f'0x{b:02X},' for b in data[start:start + 19]))
    lines.append('};')
    lines.append(f'inline constexpr uint16_t CAT_DEFAULT_BYTES = {len(data)};')
    names = ', '.join(name for name, _ in AVATARS)
    lines.append(f'inline constexpr const uint8_t* ALL[] = {{{names}}};')
    lines.append(f'inline constexpr uint16_t BYTES[] = {{{", ".join(str(n) for n in lengths)}}};')
    lines.append(f'inline constexpr int COUNT = {len(AVATARS)};')
    lines.append('}  // namespace RickyAvatars')
    return '\n'.join(lines) + '\n'


def drawn(image: Image.Image, size: int) -> Image.Image:
    """The firmware's 16-level draw: area-sampled coverage inside the circle, anti-aliased ring."""
    small = image.resize((size, size), Image.BOX) if size < SIZE else image
    paper = small.point(lambda c: 255 - c * 17)
    scale = 4
    mask = Image.new('L', (size * scale, size * scale), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size * scale - 1, size * scale - 1), fill=255)
    mask = mask.resize((size, size), Image.BOX)
    out = Image.composite(paper, Image.new('L', (size, size), 255), mask)
    ring = Image.new('L', (size * scale, size * scale), 255)
    ImageDraw.Draw(ring).ellipse((0, 0, size * scale - 1, size * scale - 1), outline=0,
                                 width=max(2, size // 48) * scale)
    ring = ring.resize((size, size), Image.BOX)
    return Image.composite(ring, out, ring.point(lambda v: 255 - v))


def preview(images, path: Path) -> None:
    sizes = (SIZE, 88, 56)
    gap = 16
    width = len(images) * (SIZE + gap) + gap
    height = gap + sum(s + gap for s in sizes)
    sheet = Image.new('L', (width, height), 255)
    y = gap
    for size in sizes:
        for i, image in enumerate(images):
            x = gap + i * (SIZE + gap) + (SIZE - size) // 2
            sheet.paste(drawn(image, size), (x, y))
        y += size + gap
    sheet.save(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=HEADER)
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    images = [to_coverage(SOURCES / f'{name}.png') for name, _ in AVATARS]
    # Its wide ears would touch the circle at the usual size.
    cat_default = to_coverage(SOURCES / f'{CAT_DEFAULT[1]}.png', fill=0.70, top=0.14)
    args.out.write_text(header_text(images, cat_default))
    if args.preview:
        preview(images + [cat_default], args.preview)


if __name__ == '__main__':
    main()
