#!/usr/bin/env python3
"""Subset the official Noto CJK outlines used by the system interface.

The checked-in headers keep normal firmware builds independent of fontTools
and of the original font files. Pass the Plus translation directory as
--translations to include its additional interface strings in the same subsets.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

from gen_i18n import parse_yaml_file

ROOT = Path(__file__).resolve().parents[1]
PINS = {
    "sc_regular": (
        "NotoSansCJKsc-Regular.otf",
        "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b",
        "chinese.yaml",
    ),
    "tc_regular": (
        "NotoSansCJKtc-Regular.otf",
        "dce08bd4fd91aa8aa76ed8fea4b694c2dfb8550f67871e326843212ddbeb88b4",
        "chinese-traditional.yaml",
    ),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, required=True)
    parser.add_argument("--translations", type=Path, action="append", default=[])
    args = parser.parse_args()

    dest = ROOT / "src/resources"
    dest.mkdir(exist_ok=True)
    translation_dirs = [ROOT / "lib/I18n/translations", *args.translations]
    report = {
        "license": "SIL OFL 1.1",
        "source": "https://github.com/notofonts/noto-cjk/tree/main/Sans/OTF",
        "faces": {},
    }

    for name, (filename, digest, language) in PINS.items():
        source = (args.sources / filename).read_bytes()
        if hashlib.sha256(source).hexdigest() != digest:
            raise SystemExit(f"Unexpected font source checksum: {filename}")

        text = "".join(
            value
            for directory in translation_dirs
            for translation in (language, "english.yaml")
            for value in parse_yaml_file(str(directory / translation)).values()
        )
        chars = {ord(char) for char in text + "繁體中文简体中文English\ufffd" if ord(char) >= 32}
        chars.update(range(32, 127))
        font = TTFont(io.BytesIO(source), recalcTimestamp=False)
        cmap = font.getBestCmap()
        missing = sorted(char for char in chars if 0x3400 <= char <= 0x9FFF and char not in cmap)
        if missing:
            raise SystemExit(f"Missing interface characters in {filename}: {missing}")

        options = subset.Options()
        options.hinting = False
        options.desubroutinize = False
        options.recalc_timestamp = False
        options.layout_features = []
        options.drop_tables += ["GSUB", "GPOS", "BASE", "VORG", "vhea", "vmtx"]
        options.name_IDs = [1, 2]
        options.name_languages = [0x409]
        options.notdef_glyph = True
        options.notdef_outline = True

        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=chars)
        subsetter.subset(font)
        output = io.BytesIO()
        font.save(output, reorderTables=True)
        data = output.getvalue()

        lines = [
            "// Generated by scripts/build_system_ui_fonts.py; SIL OFL 1.1.",
            "#pragma once",
            "#include <cstdint>",
            "namespace system_ui_font_data {",
            f"inline constexpr uint8_t {name}[] = {{",
        ]
        for i in range(0, len(data), 24):
            lines.append(" " + ",".join(f"0x{byte:02x}" for byte in data[i : i + 24]) + ",")
        lines.extend(["};", "}  // namespace system_ui_font_data", ""])
        (dest / f"SystemUiFont_{name}.h").write_text("\n".join(lines), encoding="utf-8")

        report["faces"][name] = {
            "file": filename,
            "source_sha256": digest,
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "characters": len(chars),
        }
        print(name, len(data), "bytes")

    report["total_bytes"] = sum(face["bytes"] for face in report["faces"].values())
    (dest / "system-ui-fonts.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Total outline bytes:", report["total_bytes"])


if __name__ == "__main__":
    main()
