#!/usr/bin/env python3
"""Generate the shared reader's bounded TTF warm-up character list."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib/EpdFont/scripts/cn_rickyos_group_order.txt'
OUTPUT = ROOT / 'src/ReaderCommonChars.generated.h'
COUNT = 4000


def render():
    chars = [c for c in SOURCE.read_text(encoding='utf-8') if c not in '\r\n'][:COUNT]
    data = ''.join(chars).encode('utf-8')
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return ('#pragma once\n\n'
            '// Generated by scripts/generate_reader_common_chars.py. Do not edit.\n'
            f'// First {len(chars)} characters of lib/EpdFont/scripts/cn_rickyos_group_order.txt.\n'
            '// UTF-8, NUL-terminated, common characters first.\n\n'
            '#include <cstdint>\n\n'
            'inline constexpr uint8_t kReaderCommonChars[] = {\n  ' + ',\n  '.join(rows) + ', 0x00};\n')


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUTPUT.exists() and OUTPUT.read_text() == text else 'ReaderCommonChars.generated.h is stale')
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        OUTPUT.write_text(text)
        print(f'wrote {OUTPUT.relative_to(ROOT)}')
